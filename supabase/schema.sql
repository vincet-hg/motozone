-- Scooter Land database. Run once in Supabase: SQL Editor > New query > paste > Run.

-- ---------------------------------------------------------------- tables

create table public.admins (
  user_id uuid primary key references auth.users (id) on delete cascade
);

create table public.categories (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 1 and 80),
  slug text not null unique,
  position int not null default 0
);

create table public.products (
  id uuid primary key default gen_random_uuid(),
  category_id uuid references public.categories (id) on delete restrict,
  name text not null check (char_length(name) between 1 and 200),
  slug text not null unique,
  description text not null default '',
  specs jsonb not null default '[]'::jsonb,
  compatibility text not null default '',
  price numeric(10, 2) not null check (price >= 0),
  sale_price numeric(10, 2) check (sale_price is null or (sale_price >= 0 and sale_price < price)),
  final_price numeric(10, 2) generated always as (coalesce(sale_price, price)) stored,
  stock int not null default 0 check (stock >= 0),
  images text[] not null default '{}',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create index products_newest_idx on public.products (active, created_at desc);
create index products_price_idx on public.products (active, final_price);
create index products_category_idx on public.products (category_id);

create table public.orders (
  id bigint generated by default as identity (start with 1001) primary key,
  customer_name text not null,
  phone text not null,
  city text not null,
  address text not null,
  note text not null default '',
  total numeric(10, 2) not null default 0,
  status text not null default 'new'
    check (status in ('new', 'confirmed', 'shipped', 'delivered', 'cancelled')),
  created_at timestamptz not null default now()
);

create index orders_created_idx on public.orders (created_at desc);
create index orders_phone_idx on public.orders (phone, created_at desc);

create table public.order_items (
  id bigint generated always as identity primary key,
  order_id bigint not null references public.orders (id) on delete cascade,
  -- Name and price are copied so orders stay correct after a product changes or is deleted.
  product_id uuid references public.products (id) on delete set null,
  product_name text not null,
  price numeric(10, 2) not null,
  qty int not null check (qty > 0)
);

create index order_items_order_idx on public.order_items (order_id);
create index order_items_product_idx on public.order_items (product_id);

-- ---------------------------------------------------------------- access rules

create function public.is_admin() returns boolean
language sql stable security definer set search_path = ''
as $$ select exists (select 1 from public.admins where user_id = (select auth.uid())) $$;

alter table public.admins enable row level security;
alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

create policy admins_read_own on public.admins
  for select to authenticated using (user_id = (select auth.uid()));

create policy categories_read on public.categories
  for select to anon, authenticated using (true);
create policy categories_admin_insert on public.categories
  for insert to authenticated with check ((select public.is_admin()));
create policy categories_admin_update on public.categories
  for update to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
create policy categories_admin_delete on public.categories
  for delete to authenticated using ((select public.is_admin()));

create policy products_read_active on public.products
  for select to anon, authenticated using (active or (select public.is_admin()));
create policy products_admin_insert on public.products
  for insert to authenticated with check ((select public.is_admin()));
create policy products_admin_update on public.products
  for update to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
create policy products_admin_delete on public.products
  for delete to authenticated using ((select public.is_admin()));

-- Orders are created and changed only through the two functions below.
create policy orders_admin_read on public.orders
  for select to authenticated using ((select public.is_admin()));
create policy order_items_admin_read on public.order_items
  for select to authenticated using ((select public.is_admin()));

grant select on public.admins to authenticated;
grant select on public.categories, public.products to anon, authenticated;
grant insert, update, delete on public.categories, public.products to authenticated;
grant select on public.orders, public.order_items to authenticated;

-- ---------------------------------------------------------------- orders

-- Prices and stock are read from the database, never from the browser.
-- Stock rows are locked, so two customers cannot buy the last item.
create function public.place_order(
  p_name text,
  p_phone text,
  p_city text,
  p_address text,
  p_note text,
  p_items jsonb
) returns jsonb
language plpgsql security definer set search_path = ''
as $$
declare
  v_name text := btrim(coalesce(p_name, ''));
  v_phone text := regexp_replace(coalesce(p_phone, ''), '[^0-9]', '', 'g');
  v_city text := btrim(coalesce(p_city, ''));
  v_address text := btrim(coalesce(p_address, ''));
  v_note text := btrim(coalesce(p_note, ''));
  v_order_id bigint;
  v_total numeric(10, 2) := 0;
  v_expected int;
  v_seen int := 0;
  r record;
begin
  if v_phone ~ '^995[0-9]{9}$' then
    v_phone := substr(v_phone, 4);
  end if;
  if v_phone !~ '^[0-9]{9}$' then
    raise exception 'invalid_phone';
  end if;
  if char_length(v_name) not between 2 and 100
    or char_length(v_city) not between 2 and 60
    or char_length(v_address) not between 3 and 300
    or char_length(v_note) > 500 then
    raise exception 'invalid_customer';
  end if;
  if jsonb_typeof(p_items) is distinct from 'array'
    or jsonb_array_length(p_items) not between 1 and 50 then
    raise exception 'invalid_items';
  end if;

  if (select count(*) from public.orders o
      where o.phone = v_phone and o.status = 'new'
        and o.created_at > now() - interval '1 hour') >= 5 then
    raise exception 'too_many_orders';
  end if;

  select count(distinct (e ->> 'id')::uuid) into v_expected
  from jsonb_array_elements(p_items) e;

  insert into public.orders (customer_name, phone, city, address, note)
  values (v_name, v_phone, v_city, v_address, v_note)
  returning id into v_order_id;

  for r in
    select p.id, p.name, p.final_price, p.stock, p.active, q.qty
    from (
      select (e ->> 'id')::uuid as id, sum((e ->> 'qty')::int)::int as qty
      from jsonb_array_elements(p_items) e
      group by 1
    ) q
    join public.products p on p.id = q.id
    order by p.id
    for update of p
  loop
    v_seen := v_seen + 1;
    if r.qty not between 1 and 99 then
      raise exception 'invalid_items';
    end if;
    if not r.active then
      raise exception 'product_unavailable' using detail = r.name;
    end if;
    if r.stock < r.qty then
      raise exception 'out_of_stock' using detail = r.name;
    end if;

    insert into public.order_items (order_id, product_id, product_name, price, qty)
    values (v_order_id, r.id, r.name, r.final_price, r.qty);

    update public.products set stock = stock - r.qty where id = r.id;
    v_total := v_total + r.final_price * r.qty;
  end loop;

  if v_seen <> v_expected then
    raise exception 'product_unavailable';
  end if;

  update public.orders set total = v_total where id = v_order_id;
  return jsonb_build_object('order_id', v_order_id, 'total', v_total);
end;
$$;

-- Cancelling returns the items to stock. A cancelled order stays cancelled.
create function public.set_order_status(p_order_id bigint, p_status text) returns void
language plpgsql security definer set search_path = ''
as $$
declare
  v_current text;
begin
  if not public.is_admin() then
    raise exception 'not_admin';
  end if;
  if p_status not in ('new', 'confirmed', 'shipped', 'delivered', 'cancelled') then
    raise exception 'invalid_status';
  end if;

  select status into v_current from public.orders where id = p_order_id for update;
  if v_current is null then
    raise exception 'order_not_found';
  end if;
  if v_current = p_status then
    return;
  end if;
  if v_current = 'cancelled' then
    raise exception 'order_cancelled';
  end if;

  if p_status = 'cancelled' then
    update public.products p
    set stock = p.stock + i.qty
    from public.order_items i
    where i.order_id = p_order_id and i.product_id = p.id;
  end if;

  update public.orders set status = p_status where id = p_order_id;
end;
$$;

revoke execute on function public.is_admin() from public;
revoke execute on function public.place_order(text, text, text, text, text, jsonb) from public;
revoke execute on function public.set_order_status(bigint, text) from public;
grant execute on function public.is_admin() to anon, authenticated;
grant execute on function public.place_order(text, text, text, text, text, jsonb) to anon, authenticated;
grant execute on function public.set_order_status(bigint, text) to authenticated;

