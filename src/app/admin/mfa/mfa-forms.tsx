"use client";

import { useActionState, useState, useTransition } from "react";
import { startMfaSetup, verifyMfa, type FormState, type MfaSetup } from "../actions";

const input = "mt-1 h-11 w-full rounded border border-neutral-300 px-3 text-center text-lg tracking-[0.4em]";

function CodeForm({ factorId, label }: { factorId: string; label: string }) {
  const [state, action, pending] = useActionState<FormState, FormData>(verifyMfa, {});
  return (
    <form action={action} className="space-y-3">
      <input type="hidden" name="factor_id" value={factorId} />
      <label className="block text-sm">
        {label}
        <input name="code" inputMode="numeric" autoComplete="one-time-code" pattern="[0-9 ]{6,7}" maxLength={7} required autoFocus className={input} />
      </label>
      {state.error && (
        <p role="alert" className="text-sm text-red-700">
          {state.error}
        </p>
      )}
      <button disabled={pending} className="h-11 w-full rounded bg-black font-medium text-white disabled:opacity-50">
        {pending ? "მოწმდება..." : "დადასტურება"}
      </button>
    </form>
  );
}

export function MfaChallenge({ factorId }: { factorId: string }) {
  return <CodeForm factorId={factorId} label="შეიყვანე 6-ნიშნა კოდი ავთენტიკატორის აპიდან" />;
}

export function MfaSetupForm() {
  const [setup, setSetup] = useState<MfaSetup>({});
  const [pending, startTransition] = useTransition();

  if (!setup.factorId) {
    return (
      <div className="space-y-3 text-sm leading-6">
        <p>ადმინის ანგარიშის დასაცავად შესვლისას პაროლთან ერთად ტელეფონის კოდიც დაგჭირდება.</p>
        <p>ჩამოტვირთე ავთენტიკატორის აპი, მაგალითად Google Authenticator, Microsoft Authenticator ან 1Password.</p>
        {setup.error && <p role="alert" className="text-red-700">{setup.error}</p>}
        <button
          type="button"
          disabled={pending}
          onClick={() => startTransition(async () => setSetup(await startMfaSetup()))}
          className="h-11 w-full rounded bg-black font-medium text-white disabled:opacity-50"
        >
          {pending ? "იქმნება..." : "დაყენების დაწყება"}
        </button>
      </div>
    );
  }

  return (
    <div className="space-y-3 text-sm">
      <p>აპში დაასკანერე QR კოდი:</p>
      {/* A data: URI SVG generated by Supabase for this admin only. */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img src={setup.qr} alt="QR კოდი ავთენტიკატორისთვის" className="mx-auto size-48 border border-neutral-200" />
      <details>
        <summary className="cursor-pointer">ვერ ასკანერებ? შეიყვანე კოდი ხელით</summary>
        <code className="mt-1 block rounded bg-neutral-100 p-2 text-xs break-all select-all">{setup.secret}</code>
      </details>
      <CodeForm factorId={setup.factorId} label="შემდეგ შეიყვანე აპში გამოჩენილი 6-ნიშნა კოდი" />
    </div>
  );
}
